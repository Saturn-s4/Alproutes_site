#!/usr/bin/env node
// Generates the topo symbol assets from symbols.json (the single source of truth):
//   shared/topo-symbols/svg/<id>.svg      one file per symbol, stroke = currentColor
//   shared/topo-symbols/sprite.svg        all symbols as <symbol id="topo-<id>">
//   web/src/lib/topo-symbols.data.ts      typed data for the web client
// Usage: node shared/topo-symbols/build.mjs   (no dependencies)
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const set = JSON.parse(readFileSync(join(here, 'symbols.json'), 'utf8'));

const ids = new Set();
for (const s of set.symbols) {
  if (!/^[a-z][a-z0-9_]*$/.test(s.id)) throw new Error(`bad symbol id: ${s.id}`);
  if (ids.has(s.id)) throw new Error(`duplicate symbol id: ${s.id}`);
  if (!set.groups.some((g) => g.id === s.group)) throw new Error(`${s.id}: unknown group ${s.group}`);
  if (!s.label?.ru || !s.label?.en) throw new Error(`${s.id}: label needs ru and en`);
  ids.add(s.id);
}

const esc = (t) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;');
const body = (s) => s.paths
  .map((p) => (p.fill ? `<path d="${p.d}" fill="currentColor"/>` : `<path d="${p.d}"/>`))
  .join('');
const vb = `0 0 ${set.viewBox} ${set.viewBox}`;
const strokeAttrs = `fill="none" stroke="currentColor" stroke-width="${set.strokeWidth}" stroke-linecap="round" stroke-linejoin="round"`;

const svgDir = join(here, 'svg');
rmSync(svgDir, { recursive: true, force: true });
mkdirSync(svgDir);
for (const s of set.symbols) {
  writeFileSync(join(svgDir, `${s.id}.svg`),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" width="${set.viewBox}" height="${set.viewBox}" ${strokeAttrs}>` +
    `<title>${esc(s.label.ru)} / ${esc(s.label.en)}</title>${body(s)}</svg>\n`);
}

writeFileSync(join(here, 'sprite.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n` +
  set.symbols.map((s) => `  <symbol id="topo-${s.id}" viewBox="${vb}" ${strokeAttrs}>${body(s)}</symbol>`).join('\n') +
  `\n</svg>\n`);

const ts = `// GENERATED by shared/topo-symbols/build.mjs from shared/topo-symbols/symbols.json — do not edit by hand.\n` +
  `/* eslint-disable */\n` +
  `export const TOPO_SYMBOL_SET = ${JSON.stringify(
    { viewBox: set.viewBox, strokeWidth: set.strokeWidth, groups: set.groups, symbols: set.symbols, lines: set.lines },
    null, 2)} as const;\n`;
writeFileSync(join(here, '..', '..', 'web', 'src', 'lib', 'topo-symbols.data.ts'), ts);

console.log(`topo symbols: ${set.symbols.length} symbols, ${set.lines.length} line styles`);
