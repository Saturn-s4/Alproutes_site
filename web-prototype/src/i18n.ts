const dicts: Record<Lang, Record<Key, string>> = { ru, en };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  const d = dicts[lang];
  return (key, vars) => {
    let s = d[key] ?? ru[key] ?? key;
    if (vars) for (const k in vars) s = s.split(`{${k}}`).join(String(vars[k]));
    return s;
  };
}

/** Russian-aware plural: forms = [one, few, many]; English uses one / many. */
export function plural(lang: Lang, n: number, forms: { ru: [string, string, string]; en: [string, string] }) {
  if (lang === 'en') return n === 1 ? forms.en[0] : forms.en[1];
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return forms.ru[0];
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return forms.ru[1];
  return forms.ru[2];
}
